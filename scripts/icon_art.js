const order = ['select', 'stamp', 'brush', 'biome', 'path', 'terrain', 'mirror', 'picker',
    'undo', 'redo', 'history', 'more', 'save', 'done', 'search', 'bag',
    'star', 'recent', 'all', 'tree', 'person', 'tiles', 'picture', 'face',
    'sword', 'scene', 'window', 'music', 'box', 'map', 'gear', 'sparkle',
    'sun', 'scissors', 'wrench', 'trash', 'layers', 'eye', 'lock', 'folder',
    'grid', 'sound', 'help', 'close', 'left', 'right', 'plus', 'info', 'leaf'];

module.exports = { palette, icons, order, size: 16, cols: 8 };

if (require.main === module) {
    const fs = require('fs'), path = require('path'), zlib = require('zlib');
    const { encodePng } = require('./png');
    const cols = 8, size = 16, rows = Math.ceil(order.length / cols);
    const w = cols * size, h = rows * size;
    const rgba = Buffer.alloc(w * h * 4);
    const hex = c => [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16)];
    order.forEach((name, i) => {
        const grid = icons[name];
        if (!grid) throw new Error('no icon ' + name);
        if (grid.length !== size) console.warn(`${name}: ${grid.length} rows`);
        const ox = (i % cols) * size, oy = Math.floor(i / cols) * size;
        grid.forEach((row, y) => {
            if (row.length !== size) console.warn(`${name} row ${y}: ${row.length} wide`);
            for (let x = 0; x < size; x++) {
                const ch = row[x] || '.';
                if (!(ch in palette)) throw new Error(`${name} row ${y}: unknown colour "${ch}"`);
                const c = palette[ch];
                if (!c) continue;
                const [r, g, b] = hex(c), at = ((oy + y) * w + ox + x) * 4;
                rgba[at] = r; rgba[at + 1] = g; rgba[at + 2] = b; rgba[at + 3] = 255;
            }
        });
    });
    const out = path.join(__dirname, '..', 'art');
    fs.mkdirSync(out, { recursive: true });
    fs.writeFileSync(path.join(out, 'ui_icons.png'), encodePng(w, h, rgba, d => zlib.deflateSync(d)));
    fs.writeFileSync(path.join(out, 'ui_icons.json'), JSON.stringify({ size, cols, names: order }, null, 2) + '\n');
    console.log(`art/ui_icons.png: ${order.length} icons, ${w}x${h}`);
}
