'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine');
E.install(); E.setupWorld();
require('../Docs-Doodads.js');
const D = DocsDoodads, B = D.Beat;
assert.ok(B, 'shared BGM spectrum exists');
let made = 0, reads = 0, level = 0, connected = 0, disconnected = 0;
const analyser = { frequencyBinCount: 256, disconnect() {}, getByteFrequencyData(bytes) { reads++; bytes.fill(level); } };
const gain = { gain: { value: 1 }, connect(node) { assert.strictEqual(node, analyser); connected++; }, disconnect(node) { assert.strictEqual(node, analyser); disconnected++; } };
global.WebAudio = { _context: { state: 'running', sampleRate: 48000, createAnalyser() { made++; return analyser; } }, _masterGainNode: { gain: { value: 1 } } };
global.AudioManager = { _bgmBuffer: { _gainNode: gain, isPlaying: () => true }, bgmVolume: 100 };
Graphics.frameCount = 1;
B.idle(); assert.strictEqual(made, 0, 'no analyser on a map without a consumer');
assert.deepStrictEqual(B.snapshot(), { low: 0, mid: 0, high: 0, kick: false });
assert.strictEqual(made, 1); assert.strictEqual(connected, 1);
level = 255; Graphics.frameCount++;
const step = B.snapshot();
assert.ok(step.low > 0 && step.low < 1, 'spectrum bands ease toward a step');
assert.strictEqual(step.kick, true);
const before = reads;
for (let i = 0; i < 200; i++) B.factor('low', 1);
assert.strictEqual(reads, before, 'all doodads share one read per frame');
Graphics.frameCount++;
assert.strictEqual(B.snapshot().kick, false, 'sustained audio is not repeated kicks');
const motion = D.Motion.normalize({ type: 'bob', amount: 1, speed: 1, musicBand: 'low', musicStrength: 1 });
const quiet = D.Motion.sample(motion, 0.5, 0, 0);
assert.ok(Math.abs(quiet.offsetY) < 6);
AudioManager.bgmVolume = 0; Graphics.frameCount++;
assert.deepStrictEqual(B.snapshot(), { low: 0, mid: 0, high: 0, kick: false }, 'muted audio has zero bands');
assert.strictEqual(B.factor('low', 1), 0);
assert.strictEqual(B.factor('none', 1), 1);
assert.strictEqual(D.Motion.sample(motion, 0.5, 0, 0).offsetY, 0);
const lamps = D.Lighting.collect([{ x: 100, y: 100, light: { enabled: true, intensity: 1, musicBand: 'low', musicStrength: 1 } }]);
assert.strictEqual(lamps[0].intensity, 0, 'music-reactive lamps go quiet with audio');
assert.ok(disconnected > 0, 'disconnect only the analyser tap, preserving the BGM output');
AudioManager.bgmVolume = 100; Graphics.frameCount++;
B.snapshot(); Graphics.frameCount += 3; B.idle();
assert.strictEqual(B.node, null, 'unused analysers are released after consumers leave');
AudioManager._bgmBuffer = null; Graphics.frameCount++;
assert.deepStrictEqual(D.api.beat(), { low: 0, mid: 0, high: 0, kick: false });
const config = D.Particles.normalize({ preset: 'embers', musicTrigger: 'kick' });
assert.strictEqual(config.musicTrigger, 'kick');
const state = D.Particles.createState(config, 1);
D.Particles.step(state, 1 / 60, true);
assert.strictEqual(state.particles.length, 0, 'Kick emitters stay quiet without audio');
assert.ok(D.Workspace.effectSections().find(s => s.title === 'Motion').fields.some(f => f.key === 'motion.musicBand'));
console.log('BGM beat: lazy audio tap, easing, kicks, shared reads, silence, motion, lights and particles passed.');
