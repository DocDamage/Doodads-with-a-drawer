'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine'); E.install(); E.setupWorld();
require('../Docs-Doodads.js');
const D = DocsDoodads, S = D.Shipped, W = D.WorldState;
assert.ok(S, 'released-save compatibility rules exist');
const gate = { uid: 'gate', name: 'Gate', x: 48, y: 96, bit: [3, 'img/Gate.png'], states: { list: [{ name: 'Closed' }, { name: 'Open' }] } };
const data = { 1: [gate] };
const snap = S.snapshot(data, { 1: [20, 15] }, 'first');
assert.strictEqual(S.diff(null, S.snapshot(data, {})).length, 0, 'no release means no warnings');
assert.strictEqual(S.diff(snap, S.snapshot(data, { 1: [20, 15] })).length, 0);
const changed = JSON.parse(JSON.stringify(data)); changed[1][0].name = 'Door';
assert.ok(S.diff(snap, S.snapshot(changed, { 1: [20, 15] })).some(p => p.type === 'renamed' && p.oldName === 'Gate' && p.newName === 'Door'));
assert.ok(S.diff(snap, S.snapshot({ 1: [] }, { 1: [20, 15] })).some(p => p.type === 'nameGone'));
changed[1][0].name = 'Gate'; changed[1][0].states.list.reverse();
assert.ok(S.diff(snap, S.snapshot(changed, { 1: [20, 15] })).some(p => p.type === 'stateMoved'));
changed[1][0].states.list.pop();
assert.ok(S.diff(snap, S.snapshot(changed, { 1: [20, 15] })).some(p => p.type === 'stateGone'));
assert.ok(S.diff(snap, S.snapshot(data, { 1: [21, 15] })).some(p => p.type === 'mapResized'));
const renamed = JSON.parse(JSON.stringify(gate)); renamed.name = 'Entrance';
$dataDocsDoodads[1] = [renamed];
$dataDocsDoodads.aliases = { 1: { gate: 'Door', door: 'Entrance' } };
$gameSystem._docsWorldState = { states: { '1/name:gate': 1, '1/name:gone': 2, '2/name:other': 1 }, lights: { '1/name:gate': false } };
S.migrateSaved(1);
assert.strictEqual(W.state('Gate', 1), 'Open', 'old state follows a chain of renamed names');
assert.strictEqual(W.light('Gate', 1), false, 'old light follows the same alias');
assert.ok(!('1/name:gone' in W.store().states), 'deleted names are pruned only on the loaded map');
assert.strictEqual(W.store().states['2/name:other'], 1);
assert.strictEqual(W.setState('Door', 0, 1), true);
assert.strictEqual(W.store().states['1/name:entrance'], 'Closed', 'new numeric sets persist the actual state name');
assert.strictEqual(W.setState('Entrance', 'next', 1), true);
assert.strictEqual(W.store().states['1/name:entrance'], 'Open');
W.store().states['1/name:entrance'] = 0;
assert.strictEqual(D.States.index(renamed, 1), 0, 'numbers from older saves still read');
const numericNamed = { states: { list: [{ name: '2' }, { name: 'Other' }] } };
assert.strictEqual(D.States.find(numericNamed, '2'), 0, 'a stored numeric-looking state name is still a name');
assert.strictEqual(D.States.find(numericNamed, 1), 1, 'a number still selects an index');
numericNamed.name = 'Numeric'; $dataDocsDoodads[1].push(numericNamed);
assert.strictEqual(W.setState('Numeric', 2, 1), false, 'invalid numeric indices do not accidentally select a numeric-looking name');
assert.strictEqual(W.setState('Numeric', '2', 1), true);
assert.strictEqual(D.States.index(numericNamed, 1), 0);
assert.strictEqual(S.resolveName({ 1: { a: 'B', b: 'A' } }, 1, 'A'), 'a', 'cyclic author aliases terminate safely');
for (const split of [false, true]) {
    const entries = D.DataFiles.entriesFor($dataDocsDoodads, split), files = Object.fromEntries(entries.map(entry => [entry.path, entry.data]));
    const read = D.DataFiles.merge(entries[0].data, id => files[D.DataFiles.mapPath(id)]);
    assert.deepStrictEqual(read.aliases, $dataDocsDoodads.aliases);
}
console.log('Released saves: snapshot differences, rename chains, states/lights, old numbers and aliases passed.');
