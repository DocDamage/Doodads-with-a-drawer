'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine');
E.install(); E.setupWorld({ width: 20, height: 20, px: 3, py: 2 });
require('../Docs-Doodads.js');
const D = DocsDoodads, N = D.Near;
assert.ok(N, 'nearness triggers exist');
const door = E.doodad(5, 2, { name: 'Gate', uid: 'gate', near: { range: 2, enter: 'Open', leave: 'Closed', commonEventId: 1, once: true } });
door.states = { list: [{ name: 'Closed' }, { name: 'Open' }], by: 'manual' };
assert.strictEqual(N.inside(door, 3, 2, 48, 48), true);
assert.strictEqual(N.inside(door, 2.8, 2, 48, 48), false);
assert.strictEqual(N.inside(door, 2.8, 2, 48, 48, null, true), true, 'half-tile exit slack');
assert.strictEqual(N.inside(door, 2.4, 2, 48, 48, null, true), false);
const seam = E.doodad(0, 2, { near: { range: 1 } });
assert.strictEqual(N.inside(seam, 19, 2, 48, 48, { w: 20, h: 0 }), true);
assert.strictEqual(N.step(false, true), 'enter');
assert.strictEqual(N.step(true, false), 'leave');
assert.strictEqual(N.step(true, true), null);
$dataDocsDoodads[1] = [door];
const states = [], events = [];
D.WorldState.setState = (d, name) => { states.push(name); return true; };
let reserved = false;
$gameTemp.reserveCommonEvent = () => { events.push(1); reserved = true; };
$gameTemp.isCommonEventReserved = () => reserved;
const seen = [];
D.api.on('near', d => seen.push(d.name));
const ss = new Spriteset_Map();
const tick = () => { for (let i = 0; i < 6; i++) ss.updateDocsNear(); };
tick();
assert.deepStrictEqual(states, ['Open']);
assert.deepStrictEqual(seen, ['Gate']);
assert.strictEqual(events.length, 1);
$gamePlayer.x = 2.8;
tick(); assert.strictEqual(states.length, 1);
$gamePlayer.x = 1;
tick(); assert.deepStrictEqual(states, ['Open', 'Closed']);
assert.strictEqual(events.length, 1, 'a reserved common event is never queued twice');
$gamePlayer.x = 3;
tick(); assert.strictEqual(states.length, 2, 'once does not enter twice');
const saved = JSON.parse(JSON.stringify($gameSystem._docsNearOnce));
$gameSystem._docsNearOnce = saved;
const loaded = new Spriteset_Map();
for (let i = 0; i < 6; i++) loaded.updateDocsNear();
assert.strictEqual(states.length, 2, 'once persists after reloading');
$dataDocsDoodads[1] = [];
ss.updateDocsNear();
assert.strictEqual(ss._docsNearEntries.length, 0);
const emptyTick = ss._docsNearTick;
for (let i = 0; i < 120; i++) ss.updateDocsNear();
assert.strictEqual(ss._docsNearTick, emptyTick, 'no per-frame checks without near doodads');
assert.ok(D.Workspace.effectSections().some(s => s.title === 'When the player is near'));
console.log('Nearness triggers: all tests passed.');
