'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine');
E.install(); E.setupWorld();
global.Game_Screen = class {
    constructor() { this._weatherType = 'none'; this._weatherPower = 0; this.calls = []; }
    changeWeather(type, power, duration) { this._weatherType = type; this._weatherPower = power; this.calls.push({ type, power, duration }); }
    weatherType() { return this._weatherType; }
    weatherPower() { return this._weatherPower; }
};
global.$gameScreen = new Game_Screen();
require('../Docs-Doodads.js');
const D = DocsDoodads, C = D.Climate, W = D.Workspace;
assert.ok(C, 'seeded climate exists');
const table = { Spring: [{ type: 'rain', power: 5, chance: 70, hours: 24 }, { type: 'none', chance: 30, hours: 24 }] };
assert.deepStrictEqual(C.day(12, 'Spring', table, 123), C.day(12, 'Spring', table, 123));
let rain = 0;
for (let day = 1; day <= 5000; day++) if (C.day(day, 'Spring', table, 123)[0].type === 'rain') rain++;
assert.ok(rain > 3200 && rain < 3800, 'weighted weather shares match the table');
assert.deepStrictEqual(C.day(1, 'Unknown', table, 1), [{ start: 0, end: 1440, type: 'none', power: 0 }]);
const spans = C.day(42, 'Spring', { Spring: [{ type: 'fog', chance: 100, hours: 4, power: 6 }] }, 1);
assert.strictEqual(spans[0].start, 0); assert.strictEqual(spans[spans.length - 1].end, 1440);
assert.ok(spans.every((span, i) => span.end > span.start && (!i || span.start === spans[i - 1].end)));
D.World.set('time.source', 'clock'); D.World.set('seasons.source', 'system');
D.World.set('climate', { enabled: true, seed: 321, seasons: { Spring: [{ type: 'storm', power: 7, chance: 100, hours: 6 }] } });
$gameSystem._docsSeason = 0;
SceneManager._scene = new Scene_Map();
const beforeRead = JSON.stringify($gameSystem._docsClimate);
const forecast = D.api.forecast(7);
assert.strictEqual(forecast.length, 7); assert.strictEqual(JSON.stringify($gameSystem._docsClimate), beforeRead, 'forecast reads do not create save state');
assert.ok(PluginManager._commands['Docs-Doodads:resumeClimate'] && PluginManager._commands['Docs-Doodads:storeForecast']);
C.update(true);
assert.strictEqual($gameScreen.weatherType(), 'storm');
assert.deepStrictEqual(Object.keys($gameSystem._docsClimate).sort(), ['held', 'seed']);
assert.strictEqual($gameSystem._docsClimate.seed, 321); assert.strictEqual($gameSystem._docsClimate.held, false);
const applied = $gameScreen.calls.length;
C.update(true); assert.strictEqual($gameScreen.calls.length, applied, 'one change per span');
$gameScreen.changeWeather('rain', 2, 0);
assert.strictEqual($gameSystem._docsClimate.held, true);
C.update(true); assert.strictEqual($gameScreen.weatherPower(), 2, 'maker weather holds');
window.$dataDocsDoodads.mapSettings = { 1: { climate: 'none' } };
assert.strictEqual($gameScreen.weatherType(), 'none', 'indoors hides even held native weather');
assert.strictEqual($gameScreen._weatherType, 'rain', 'suppression preserves native weather for returning outside');
window.$dataDocsDoodads.mapSettings[1].climate = 'world';
assert.strictEqual($gameScreen.weatherType(), 'rain');
D.api.resumeClimate(); C.update(true); assert.strictEqual($gameScreen.weatherType(), 'storm');
D.World.set('climate.seasons', { Spring: [{ type: 'fog', chance: 100, power: 8, hours: 24 }] });
C.update(true);
assert.strictEqual($gameScreen.weatherType(), 'none');
const authored = { layers2d: [{ image: 'Clouds' }] }, snapshot = JSON.stringify(authored);
const fog = C.mapLayers(authored);
assert.strictEqual(fog.layers2d.length, 2); assert.strictEqual(fog.layers2d[1].image, '#fog');
assert.strictEqual(C.mapLayers(authored), fog, 'fog layer identity stays stable inside a span');
assert.strictEqual(JSON.stringify(authored), snapshot, 'temporary fog never edits map data');
assert.ok(C.perspective({ fogStart: 10, fogEnd: 60 }).fogEnd < 60, '3D fog follows climate');
D.World.set('climate.seasons', { Spring: [{ type: 'windy', chance: 100, power: 9, hours: 24 }] });
C.update(true); assert.strictEqual($gameScreen.weatherType(), 'none'); assert.strictEqual($gameSystem._docsWind.to, 1);
const calls = $gameScreen.calls.length;
SceneManager._scene = {}; D.Calendar.addDays(1); C.update(true); assert.strictEqual($gameScreen.calls.length, calls, 'menus do not change weather');
SceneManager._scene = new Scene_Map(); C.update(true); assert.ok($gameScreen.calls.length > calls);
const saved = JSON.parse(JSON.stringify($gameSystem._docsClimate));
D.World.set('climate.seed', 999); assert.strictEqual(C.seed(), saved.seed, 'existing saves keep their seed');
$gameSystem._docsClimate = saved; C.reset();
assert.deepStrictEqual(D.api.forecast(2), D.api.forecast(2));
PluginManager.callCommand(null, 'Docs-Doodads', 'storeForecast', { days: '2', variableId: '9' });
assert.ok(String($gameVariables.value(9)).includes('Day'));
assert.ok(W.renderClimateEditor().includes('Spring') && W.renderClimateForecast().includes('Day'));
assert.ok(W.worldSections().some(section => section.title === 'Climate'));
console.log('PASS seeded climate, shares, held weather, interiors, fog/wind, forecast and calendar lifecycle');
