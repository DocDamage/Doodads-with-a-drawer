'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine');
E.install();
E.setupWorld({ width: 20, height: 20 });
require('../Docs-Doodads.js');
const D = DocsDoodads, W = D.Workspace;
assert.ok(D.Moods, 'Moods are available in the editor');
assert.ok(D.Moods.list().length >= 8);
for (const mood of D.Moods.list()) {
    assert.ok(D.PostFX.presetLook(mood.look), mood.id + ' has a screen look');
    assert.ok(D.Moods.apply(1, mood).ambient);
}
W.mounted = true;
W.refreshSpriteset = W.refreshInspector = W.updateUndoButtons = () => {};
const original = { ambient: { darkness: 0.1 }, terrain: { enabled: true }, layers2d: [{ image: 'MyCloud' }] };
D.Lighting.setMapSettings(1, D.Moods.clone(original));
D.Persistence.dirtyDoodads = false;
W.previewMinutes = 400;
$gameScreen._weatherType = 'snow';
$gameScreen._weatherPower = 3;
$gameScreen._weatherPowerTarget = 4;
$gameScreen._weatherDuration = 60;
$gameSystem._docsWind = { from: 0.1, to: 0.2, frames: 30, elapsed: 10 };
const wind = D.Moods.clone($gameSystem._docsWind);
assert.strictEqual(W.previewMood('rainy-forest'), true);
assert.strictEqual($gameScreen._weatherType, 'rain');
assert.deepStrictEqual($dataDocsDoodads.mapSettings[1], original, 'autosave only sees the original map data');
assert.strictEqual(D.Persistence.dirtyDoodads, false, 'hover is not an unsaved edit');
assert.strictEqual(D.Undo.undoStack.length, 0);
W.previewMood('cave');
assert.strictEqual(D.Lighting.mapSettings(1).layers2d.length, 1, 'mood fog does not accumulate');
W.endMoodPreview();
assert.deepStrictEqual(D.Lighting.mapSettings(1), original);
assert.strictEqual(W.previewMinutes, 400);
assert.deepStrictEqual($gameSystem._docsWind, wind);
assert.strictEqual($gameScreen._weatherPowerTarget, 4);
assert.strictEqual($gameScreen._weatherDuration, 60);
assert.strictEqual(D.Persistence.dirtyDoodads, false);
assert.strictEqual(W.previewMood('missing'), false);
W.previewMood('rainy-forest');
const changed = W.applyMood('cosy-night-village');
assert.ok(changed);
assert.strictEqual(D.Undo.undoStack.length, 1, 'apply is one step');
assert.strictEqual(changed.mood, 'cosy-night-village');
assert.deepStrictEqual(changed.terrain, original.terrain);
assert.deepStrictEqual(changed.layers2d, original.layers2d);
assert.strictEqual($gameScreen._weatherType, 'snow', 'weather stays a preview only');
D.Undo.undo();
assert.deepStrictEqual(D.Lighting.mapSettings(1), original);
D.Undo.redo();
assert.strictEqual(D.Lighting.mapSettings(1).mood, 'cosy-night-village');
const copied = D.MapSettingsCopy.apply({}, changed, D.MapSettingsCopy.parts.map(p => p.id));
assert.strictEqual(copied.mood, changed.mood);
let writes = 0;
D.FS.atomicWriteJson = () => { writes++; return true; };
D.MapPresets.data = { version: 1, presets: [] };
W.saveMood('My evening');
assert.strictEqual(writes, 1);
assert.strictEqual(D.MapPresets.get('My evening').mood, true);
assert.strictEqual(D.Moods.get('user:My evening').time, 400);
assert.strictEqual(D.MapPresets.remove('cosy-night-village'), false);
assert.strictEqual(D.Moods.get('cosy-night-village').builtIn, true);
assert.ok(W.menus().find(m => m.id === 'map').items.some(i => i.id === 'dd-moods-btn'));
W.previewMood('cave');
W.closeMoods();
assert.strictEqual(W._moodPreview, null);
assert.strictEqual(W.previewMinutes, 400);
console.log('Moods: all tests passed.');
