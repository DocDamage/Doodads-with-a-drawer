'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine'); E.install(); E.setupWorld();
require('../Docs-Doodads.js');
const D = DocsDoodads, H = D.Haze, P = D.PostFX;
assert.ok(H, 'heat haze rules exist');
const sources = Array.from({ length: 12 }, (_, i) => ({ x: 400 + i * 3, y: 300, haze: { radius: 80, strength: 3, speed: 1 } }));
sources.push({ x: -1000, y: -1000, haze: { radius: 20, strength: 8 } });
const got = H.collect(sources, { width: 816, height: 624 }, 8);
assert.strictEqual(got.length, 8);
for (let i = 1; i < got.length; i++) assert.ok(got[i].distance >= got[i - 1].distance);
assert.ok(got.every(source => source.x > 0));
assert.deepStrictEqual(H.collect([{ x: 0, y: 0 }], { width: 816, height: 624 }), []);
assert.strictEqual(H.uniforms(got, 1, false).uHaze[3], 3);
assert.strictEqual(H.uniforms(got, 1, true).uHaze[3], 1.5, 'Less Camera Motion halves displacement');
assert.deepStrictEqual(P.passes(null, 'high', null, []), []);
assert.strictEqual(P.passes(null, 'high', null, got)[0], 'haze');
assert.ok(!P.passes(null, 'low', null, got).includes('haze'));
assert.ok(!P.passes(null, 'off', null, got).includes('haze'));
assert.strictEqual(H.normalize({ preset: 'lava' }).strength > H.normalize({ preset: 'campfire' }).strength, true);
assert.strictEqual(H.normalize({ preset: 'desert' }).shape, 'band');
assert.strictEqual(H.normalize({ preset: 'underwater' }).shape, 'screen');
assert.ok(P.presets.some(preset => preset.id === 'heat'));
assert.match(H.fragment, /for \(int i = 0; i < 8; i\+\+\)/);
assert.ok(!/texture\(/.test(H.fragment), 'WebGL 1 sampler syntax');
$dataDocsDoodads[1] = [E.doodad(2, 2, { haze: { preset: 'campfire' } })];
const ss = new Spriteset_Map(); E.frames(ss, 2);
assert.ok(ss._docsPostFx && ss._docsPostFx.haze, 'the actual map builds the heat filter lazily');
assert.ok(ss._baseSprite.filters.includes(ss._docsPostFx.haze));
ConfigManager.docsFxQuality = 2; ss.updateDocsPostFx();
assert.ok(!(ss._baseSprite.filters || []).includes(ss._docsPostFx.haze), 'Low immediately detaches the pass');
ConfigManager.docsFxQuality = 0; ss._docs3d = {}; ss.updateDocsPostFx();
assert.ok(!(ss._baseSprite.filters || []).includes(ss._docsPostFx.haze), 'first version is offered only in flat maps');
assert.ok(D.Workspace.effectSections().some(section => section.title === 'Heat haze'));
console.log('Heat haze: visible nearest eight, presets, no empty/low/3D pass and comfort strength passed.');
