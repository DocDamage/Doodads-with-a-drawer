'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const E = require('./engine/fake_engine');
const { encodePng } = require('../scripts/png');
E.install(); E.setupWorld({ width: 10, height: 10 });
require('../Docs-Doodads.js');
const D = DocsDoodads, T = D.Trace, W = D.Workspace;
assert.ok(T, 'trace picture rules exist');
const fit = T.fitTwo({ x: 0, y: 0 }, { x: 100, y: 0 }, { x: 48, y: 96 }, { x: 48, y: 296 });
assert.ok(Math.abs(fit.scale - 2) < 1e-9);
assert.ok(Math.abs(fit.turn - 90) < 1e-9);
assert.ok(Math.abs(fit.x - 48) < 1e-9 && Math.abs(fit.y - 96) < 1e-9);
assert.strictEqual(T.fitTwo({ x: 0, y: 0 }, { x: 0, y: 0 }, { x: 1, y: 1 }, { x: 2, y: 2 }), null);
const point = T.point(fit, { x: 30, y: 40 });
const back = T.inverse(fit, point);
assert.ok(Math.abs(back.x - 30) < 1e-9 && Math.abs(back.y - 40) < 1e-9);
assert.deepStrictEqual(T.fitMap(256, 128, 480, 480), { x: 0, y: 120, scale: 1.875, turn: 0 });
assert.deepStrictEqual(T.unwrap({ x: 20, y: 5 }, { x: 470, y: 470 }, { w: 480, h: 480 }), { x: 500, y: 485 });
const setting = { file: 'data/docs_doodads_cache/trace/' + 'a'.repeat(64) + '.png', width: 256, height: 128, x: 12, y: 24, scale: 1, turn: 0, alpha: 0.4, show: true, locked: true };
assert.strictEqual(T.normalize(Object.assign({}, setting, { file: '../private.png' })), null);
for (const split of [false, true]) {
    const data = { 1: [], trace: { 1: setting } };
    const entries = D.DataFiles.entriesFor(data, split);
    const files = Object.fromEntries(entries.map(e => [e.path, e.data]));
    const restored = D.DataFiles.merge(entries[0].data, id => files[D.DataFiles.mapPath(id)]);
    assert.deepStrictEqual(restored.trace[1], setting, 'trace survives ' + (split ? 'split' : 'single') + ' data');
    assert.ok(!('trace' in D.DataFiles.entriesFor({ trace: {} }, split)[0].data), 'empty trace key is pruned');
}
assert.deepStrictEqual(D.RequiredAssets.collect({ doodads: { trace: { 1: setting } } }), [], 'editor picture is never deployed as required art');
W.refreshInspector = W.refreshSpriteset = W.updateUndoButtons = () => {};
W.showToast = () => {};
W.mounted = true;
W.changeTrace(setting, 'Trace picture');
assert.strictEqual(D.Undo.undoStack.length, 1);
D.Undo.undo(); assert.ok(!$dataDocsDoodads.trace);
D.Undo.redo(); assert.strictEqual($dataDocsDoodads.trace[1].file, setting.file);
assert.strictEqual(W.beginTraceDrag({ clientX: 1, clientY: 1 }), false, 'locked trace cannot catch placement');
let currentMap = 1;
$gameMap.mapId = () => currentMap;
const image = path.resolve('source.png');
fs.writeFileSync(image, encodePng(4, 2, new Uint8Array(32).fill(255), zlib.deflateSync));
(async () => {
    const imported = await W.importTrace(image, async () => ({ width: 4, height: 2 }));
    assert.ok(imported && T.normalize(imported));
    assert.ok(fs.existsSync(imported.file));
    assert.deepStrictEqual(fs.readFileSync(imported.file), fs.readFileSync(image));
    assert.strictEqual(imported.locked, true);
    const before = JSON.stringify($dataDocsDoodads);
    await W.importTrace(image, async () => { currentMap = 2; return { width: 4, height: 2 }; });
    assert.strictEqual(JSON.stringify($dataDocsDoodads), before, 'map change during loading does not edit another map');
    currentMap = 1;
    Utils.isOptionValid = () => false;
    await assert.rejects(() => W.importTrace(image, async () => ({ width: 4, height: 2 })), /playtest/);
    Utils.isOptionValid = option => option === 'test';
    const normalizer = T.normalize;
    let normalizations = 0;
    T.normalize = function(value) { normalizations++; return normalizer.call(this, value); };
    for (let i = 0; i < 20; i++) W.traceHere();
    T.normalize = normalizer;
    assert.ok(normalizations <= 1, 'unchanged trace rules are cached instead of allocated every frame');

    W.clientToMapCoords = (x, y) => ({ x, y, tileX: Math.floor(x / 48), tileY: Math.floor(y / 48) });
    W.changeTrace(Object.assign({}, imported, { locked: false }));
    D.Undo.clear();
    const centre = T.point(W.traceHere(), { x: 2, y: 1 });
    assert.strictEqual(W.beginTraceDrag({ clientX: centre.x, clientY: centre.y }), true);
    W.moveTraceDrag({ clientX: centre.x + 20, clientY: centre.y + 30 });
    assert.strictEqual(W.endTraceDrag(), true);
    assert.strictEqual(D.Undo.undoStack.length, 1, 'a drag is one undo step');
    assert.strictEqual(W.traceHere().x, imported.x + 20);
    D.Undo.undo(); assert.strictEqual(W.traceHere().x, imported.x);
    D.Undo.redo();
    let t = W.traceHere(), handle = T.handles(t).scale;
    W.beginTraceDrag({ clientX: handle.x, clientY: handle.y });
    W.moveTraceDrag({ clientX: t.x + (handle.x - t.x) * 2, clientY: t.y + (handle.y - t.y) * 2 });
    W.endTraceDrag();
    assert.ok(Math.abs(W.traceHere().scale - t.scale * 2) < 1e-9);
    t = W.traceHere();
    handle = T.handles(t).rotate;
    const pivot = T.point(t, { x: t.width / 2, y: t.height / 2 });
    W.beginTraceDrag({ clientX: handle.x, clientY: handle.y });
    W.moveTraceDrag({ clientX: pivot.x - (handle.y - pivot.y), clientY: pivot.y + (handle.x - pivot.x) });
    W.endTraceDrag();
    assert.ok(Math.abs(W.traceHere().turn - 90) < 1e-9, 'round handle turns the picture');
    const fixed = T.point(W.traceHere(), { x: t.width / 2, y: t.height / 2 });
    assert.ok(Math.hypot(fixed.x - pivot.x, fixed.y - pivot.y) < 1e-9, 'turning holds the picture centre');
    t = W.traceHere();
    W.beginTraceFit();
    W.traceFitClick(T.point(t, { x: 0, y: 0 }));
    W.traceFitClick(T.point(t, { x: 4, y: 0 }));
    W.traceFitClick({ x: 72, y: 72, tileX: 1, tileY: 1 });
    W.traceFitClick({ x: 168, y: 72, tileX: 3, tileY: 1 });
    assert.strictEqual(W.traceHere().locked, true);
    assert.ok(Math.abs(W.traceHere().scale - 24) < 1e-9, 'four clicks align picture landmarks to tile centres');
    W.beginTraceFit(); currentMap = 2;
    W.traceFitClick({ x: 0, y: 0, tileX: 0, tileY: 0 });
    assert.strictEqual(W.placementTool, null, 'a map change cannot leave clicks trapped in the fit tool');
    assert.strictEqual(W._traceFit, null);
    currentMap = 1;
    W.beginTraceFit(); t = W.traceHere();
    W.traceFitClick(T.point(t, { x: 0, y: 0 })); W.traceFitClick(T.point(t, { x: 4, y: 0 }));
    W.traceFitClick({ x: -24, y: -24, tileX: -1, tileY: -1 });
    assert.strictEqual(W._traceFit.target.length, 0, 'off-map canvas margins are not fit targets');
    W.setPlacementTool(null);
    W.changeTrace(Object.assign({}, imported, { x: 440, y: 440, scale: 24, locked: false }));
    $gameMap.isLoopHorizontal = $gameMap.isLoopVertical = () => true;
    assert.strictEqual(W.beginTraceDrag({ clientX: 8, clientY: 464 }), true);
    W.moveTraceDrag({ clientX: 28, clientY: 4 }); W.endTraceDrag();
    assert.strictEqual(W.traceHere().x, 460);
    assert.strictEqual(W.traceHere().y, 460, 'crossing both seams moves twenty pixels, not almost a map');
    W.changeTrace(Object.assign({}, imported, { x: 0, y: 0, scale: 24, turn: 0, locked: true }));
    W.beginTraceFit(); t = W.traceHere();
    W.traceFitClick(T.point(t, { x: 0, y: 0 })); W.traceFitClick(T.point(t, { x: 4, y: 0 }));
    W.traceFitClick({ tileX: 9, tileY: 1 }); W.traceFitClick({ tileX: 0, tileY: 1 });
    assert.strictEqual(W.traceHere().scale, 12, 'two-point fitting uses the adjacent tile across a looping seam');
    assert.strictEqual(W.traceHere().turn, 0);
    $gameMap.isLoopHorizontal = $gameMap.isLoopVertical = () => false;
    W.changeTrace(Object.assign({}, imported, { scale: 24, locked: true }));
    const display = new Spriteset_Map();
    SceneManager._scene = { _spriteset: display };
    display.updateDocsEditorOverlay();
    assert.ok(display._docsTraceSprite.visible);
    assert.ok(display._baseSprite.children.indexOf(display._docsTraceSprite) < display._baseSprite.children.indexOf(display._docsSelectionOutline), 'picture is below the grid');
    $gameMap.isLoopHorizontal = $gameMap.isLoopVertical = () => true;
    display.updateDocsEditorOverlay();
    assert.strictEqual(display._docsTraceSprite._docsCopies.length, 9, 'seam neighbours share a bounded image pool');
    assert.ok(display._docsTraceSprite._docsCopies.some(copy => copy.x === display._docsTraceSprite._docsCopies[4].x - 480));
    $gameMap.isLoopHorizontal = $gameMap.isLoopVertical = () => false;
    W.mounted = false; display.updateDocsEditorOverlay();
    assert.strictEqual(display._docsTraceSprite.visible, false, 'trace never appears in play');
    W.mounted = true;
    display._docs3d = true; display.updateDocsEditorOverlay();
    assert.strictEqual(display._docsTraceSprite.visible, false, 'flat tracing layer is not a 3D billboard');
    display._docs3d = null;
    const renderer = D.Compat.getRenderer(), render = renderer.render;
    let exported = 0;
    renderer.render = function(s, texture) { assert.strictEqual(s._docsTraceSprite.visible, false, 'map export omits trace'); exported++; return render.call(this, s, texture); };
    D.MapExport.capture(display, { scale: 0.5 });
    renderer.render = render;
    assert.ok(exported > 0);
    assert.strictEqual(display._docsTraceSprite.visible, true, 'map export restores editor layer');

    const ss = new Spriteset_Map();
    ss._docsSelectionOutline = { visible: true };
    ss._docsTraceSprite = { visible: true };
    SceneManager._scene = { _spriteset: ss };
    W.renderer = () => ({ render(s) { assert.strictEqual(s._docsTraceSprite.visible, false); }, extract: { canvas: () => ({}) } });
    W.renderSceneCanvas();
    assert.strictEqual(ss._docsTraceSprite.visible, true, 'capture restores trace visibility afterwards');
    assert.ok(W.menus().find(m => m.id === 'map').items.some(i => i.id === 'dd-trace-btn'));
    assert.ok(W.toolHooks.trace && W.toolHooks.traceFit);
    console.log('Trace picture: all tests passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
