'use strict';
const assert = require('assert'), fs = require('fs');
const E = require('./engine/fake_engine'); E.install(); E.setupWorld();
require('../Docs-Doodads.js');
const D = DocsDoodads, W = D.Workspace, S = D.Shipped;
const gate = E.doodad(2, 3, { uid: 'gate', name: 'Gate', states: { list: [{ name: 'Closed' }, { name: 'Open' }] } });
$dataDocsDoodads[1] = [gate];
W.mounted = true; W.refreshInspector = W.refreshSpriteset = W.updateUndoButtons = W.showToast = W.toastUndo = () => {};
D.Persistence.dirtyDoodads = D.Persistence.dirtyMap = false;
let answer = 'keep';
D.Ui.form = async () => ({ version: '1.0', target: 'Other' });
D.Ui.choose = async () => answer;
D.Ui.confirm = async () => true;
(async () => {
    const diskChanged = JSON.parse(JSON.stringify($dataDocsDoodads)); diskChanged[1][0].name = 'External';
    D.FS.atomicWriteJson(D.DataFiles.mainPath(), diskChanged, 2);
    assert.strictEqual(await W.markAsReleased(), false, 'a live/disk mismatch cannot establish an inconsistent release');
    assert.strictEqual(fs.existsSync(S.path), false);
    D.FS.atomicWriteJson(D.DataFiles.mainPath(), $dataDocsDoodads, 2);
    D.FS.atomicWriteJson(D.Persistence.mapFilePath(1), $dataMap, 2);
    assert.strictEqual(await W.markAsReleased(), true);
    assert.ok(fs.existsSync(S.path));
    assert.strictEqual(W.shippedProblems().length, 0);
    W.selectedDoodad = gate; W.selectedDoodads = [gate];
    D.Undo.clear();
    await W.setDoodadProperty([gate], 'name', 'Door');
    assert.strictEqual(gate.name, 'Door');
    assert.strictEqual(S.resolveName($dataDocsDoodads.aliases, 1, 'Gate'), 'door');
    assert.strictEqual(D.Undo.undoStack.length, 1, 'name and alias change are one step');
    D.Undo.undo(); assert.strictEqual(gate.name, 'Gate'); assert.ok(!$dataDocsDoodads.aliases || !$dataDocsDoodads.aliases[1]);
    D.Undo.redo(); assert.strictEqual(gate.name, 'Door'); assert.strictEqual(S.resolveName($dataDocsDoodads.aliases, 1, 'Gate'), 'door');
    answer = null;
    await W.setDoodadProperty([gate], 'name', 'Canceled');
    assert.strictEqual(gate.name, 'Door');
    answer = 'keep';
    await W.setDoodadProperty([gate], 'name', 'Entrance');
    assert.strictEqual(S.resolveName($dataDocsDoodads.aliases, 1, 'Gate'), 'entrance');
    let resolveDialog;
    D.Ui.choose = () => new Promise(resolve => { resolveDialog = resolve; });
    const stale = W.setDoodadProperty([gate], 'name', 'Wrong');
    W.selectedDoodad = null; W.selectedDoodads = [];
    resolveDialog('keep'); await stale;
    assert.strictEqual(gate.name, 'Entrance', 'a dialog cannot apply after selection changes');
    W.selectedDoodad = gate; W.selectedDoodads = [gate];
    D.Ui.choose = async () => answer;
    answer = null;
    await W.deleteSelectedDoodad();
    assert.ok($dataDocsDoodads[1].includes(gate), 'cancel keeps a released named doodad');
    answer = 'change';
    await W.deleteSelectedDoodad();
    assert.ok(!$dataDocsDoodads[1].includes(gate));
    D.Undo.undo(); assert.ok($dataDocsDoodads[1].includes(gate));
    const replacement = E.doodad(4, 4, { name: 'Other', states: { list: [{ name: 'Closed' }, { name: 'Open' }] } });
    $dataDocsDoodads[1].push(replacement);
    W.selectedDoodad = gate; W.selectedDoodads = [gate];
    // The replacement target can vanish while the second question is open.
    let resolveTarget;
    D.Ui.form = () => new Promise(resolve => { resolveTarget = resolve; });
    answer = 'keep';
    const staleTarget = W.deleteSelectedDoodad();
    await Promise.resolve();
    $dataDocsDoodads[1].splice($dataDocsDoodads[1].indexOf(replacement), 1);
    resolveTarget({ target: 'Other' }); await staleTarget;
    assert.ok($dataDocsDoodads[1].includes(gate));
    $dataDocsDoodads[1].push(replacement);
    D.Ui.form = async () => ({ version: '1.0', target: 'Other' });
    answer = 'keep'; await W.deleteSelectedDoodad();
    assert.ok(!$dataDocsDoodads[1].includes(gate));
    assert.strictEqual(S.resolveName($dataDocsDoodads.aliases, 1, 'Gate'), 'other', 'deletion can redirect historic names to a remaining target');
    D.Undo.undo();
    assert.ok($dataDocsDoodads[1].includes(gate));
    assert.strictEqual(S.resolveName($dataDocsDoodads.aliases, 1, 'Gate'), 'entrance');
    // Save This Map must merge only this map's aliases, keeping other maps' unsaved alias edits out.
    const DF = D.DataFiles;
    D.FS.atomicWriteJson(DF.mainPath(), { 1: [], aliases: { 2: { 'name:old': 'saved' } } });
    $dataDocsDoodads.aliases[2] = { 'name:old': 'unsaved' };
    W.mounted = false; W.mapThumb = null;
    assert.strictEqual(D.Persistence.saveMapOnly(1), true);
    const disk = DF.readAll();
    assert.strictEqual(disk.aliases[2]['name:old'], 'saved');
    assert.strictEqual(S.resolveName(disk.aliases, 1, 'Gate'), 'entrance');
    console.log('Released editor: mark, aliases, one-step undo, chained names and delete/cancel passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
