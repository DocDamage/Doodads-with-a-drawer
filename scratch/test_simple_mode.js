'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine');
E.install(); E.setupWorld();
const store = {};
global.localStorage = { getItem: k => store[k] || null, setItem: (k, v) => { store[k] = v; } };
require('../Docs-Doodads.js');
const D = DocsDoodads, S = D.SimpleMode, W = D.Workspace;
assert.ok(S, 'Simple mode exists');
assert.deepStrictEqual(S.tools(), ['select', 'stamp', 'brush', 'tiles']);
assert.strictEqual(S.defaultFor({}, false), true);
assert.strictEqual(S.defaultFor({ theme: 'dark' }, true), false);
assert.strictEqual(S.defaultFor({ simple: true }, true), true);
S.begin(); assert.strictEqual(S.enabled(), true);
assert.strictEqual(D.Ui.prefs().simple, true, 'first-run choice is kept before other preferences');
store[D.Ui.prefsKey] = JSON.stringify({ theme: 'dark' });
S.begin(); assert.strictEqual(S.enabled(), false);
assert.strictEqual(D.Ui.prefs().theme, 'dark');
const menu = [{ id: 'dd-moods-btn' }, { id: 'dd-mapset-btn' }, { id: 'dd-packs-btn' }];
assert.deepStrictEqual(S.menuItems(menu).map(i => i.id), ['dd-moods-btn', 'dd-mapset-btn']);
const sections = [{ title: 'Appearance', fields: [{ key: 'opacity' }, { key: 'blend' }] }, { title: 'Particles', fields: [] }];
assert.deepStrictEqual(S.sections(sections).map(s => s.title), ['Appearance']);
assert.deepStrictEqual(S.sections(sections)[0].fields.map(f => f.key), ['opacity']);
assert.strictEqual(sections[0].fields.length, 2, 'pure rules do not change the full list');
W.refreshInspector = W.updateUndoButtons = W.maybeStartTour = () => {};
W.setSimpleMode(false);
const full = W.paletteCommands().map(c => c.label).sort();
W.setSimpleMode(true);
assert.deepStrictEqual(W.paletteCommands().map(c => c.label).sort(), full, 'every palette command remains available');
const nodes = {};
document.getElementById = id => nodes[id] || (nodes[id] = { style: {}, classList: { toggle() {}, add() {}, remove() {} }, setAttribute() {}, querySelector: () => null });
W.updateSimpleView();
assert.strictEqual(nodes['dd-path-btn'].style.display, 'none');
assert.strictEqual(nodes['dd-stamp-btn'].style.display, '');
W.setPlacementTool('path');
assert.strictEqual(W.placementTool, 'path', 'a hidden tool still works from a shortcut or the palette');
assert.strictEqual(nodes['dd-path-btn'].style.display, '');
assert.ok(S.tools().includes('path'));
S.end(); assert.ok(!S.tools().includes('path'), 'extra tool lasts only this editor session');
console.log('Simple mode: all tests passed.');
