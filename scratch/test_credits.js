'use strict';
const assert = require('assert');
const E = require('./engine/fake_engine');
E.install(); E.setupWorld();
require('../Docs-Doodads.js');
const D = DocsDoodads, C = D.Credits, W = D.Workspace;
assert.ok(C, 'art credits ledger exists');
const root = { author: 'Ada', licence: 'CC0', source: 'https://example.test/art', note: 'Original pack' };
const leaf = { author: 'Bo', licence: 'CC-BY 4.0', source: '', note: '' };
const own = { author: 'Cy', licence: 'My own', source: '', note: '' };
const metadata = { assets: {}, folderCredits: { 'img/doodads': root, 'img/doodads/forest': leaf } };
assert.deepStrictEqual(C.of('img/doodads/forest/Oak.png', metadata), leaf);
assert.deepStrictEqual(C.of('img/doodads/forest-extra/Oak.png', metadata), root, 'folder boundaries are exact');
metadata.assets['img/doodads/forest/oak.png'] = { credit: own };
assert.deepStrictEqual(C.of('img/doodads/forest/Oak.png', metadata), own);
assert.strictEqual(C.of('../private.png', metadata), null);
const entries = [{ path: 'img/A.png', credit: root }, { path: 'img/B.png', credit: leaf }, { path: 'img/C.png', credit: own }, { path: 'img/D.png', credit: null }];
const text = C.text(entries);
for (const value of ['Ada', 'Bo', 'Cy', 'CC0', 'CC-BY 4.0', 'My own', 'img/A.png', 'img/D.png']) assert.ok(text.includes(value), value);
assert.deepStrictEqual(C.missing(entries).map(row => row.path), ['img/D.png']);
D.AssetIndex.data = metadata;
const asset = metadata.assets['img/doodads/forest/oak.png'];
Object.assign(asset, { id: 'img/doodads/forest/oak.png', path: 'img/doodads/forest/Oak.png', fileName: 'Oak.png', type: 'doodad', tags: [], autoTags: [] });
assert.strictEqual(D.Search.filter([asset], 'author:Cy licence:"My own"').length, 1);
assert.strictEqual(D.Search.filter([asset], 'credit:none').length, 0);
assert.strictEqual(D.Search.filter([asset], '-author:Cy').length, 0);
assert.strictEqual(D.Search.filter([{ ...asset, path: 'img/missing.png' }], 'credit:none').length, 1);
const pack = D.Packs.build('Credits', { contents: {}, files: [asset.path] }, () => Buffer.from('PNG'), () => asset);
assert.deepStrictEqual(D.Packs.parse(JSON.stringify(pack)).library[asset.path].credit, own, 'pack round trip retains own credits');
const inherited = { ...asset }; delete inherited.credit;
const folderPack = D.Packs.build('Folder', { contents: {}, files: [inherited.path] }, () => Buffer.from('PNG'), () => inherited);
assert.deepStrictEqual(folderPack.library[inherited.path].credit, leaf, 'inherited credits travel with the file');
let saved = 0;
D.AssetIndex.saveSoon = () => saved++;
W.setAssetCredits([asset], root);
assert.deepStrictEqual(asset.credit, root);
W.setFolderCredit('img/doodads/forest', leaf);
assert.deepStrictEqual(metadata.folderCredits['img/doodads/forest'], leaf);
assert.strictEqual(W.setFolderCredit('../elsewhere', own), false);
W.refreshUsageIndex = () => new Map([[D.Usage.keyOf(asset.path), [{}]]]);
metadata.assets['img/unused.png'] = { path: 'img/unused.png', credit: own };
assert.deepStrictEqual(W.usedCreditEntries().map(row => row.path), [asset.path], 'unused art is left out');
assert.deepStrictEqual(W.creditProblems(), [], 'missing credit check starts off');
delete asset.credit; delete metadata.folderCredits['img/doodads/forest']; delete metadata.folderCredits['img/doodads'];
D.Ui.prefs = () => ({ checkArtCredits: true });
assert.strictEqual(W.creditProblems().length, 1);
const notes = C.notesFromFiles([{ name: 'LICENSE.txt', data: Buffer.from('Offer A or B') }, { name: 'art.png', data: Buffer.from('x') }]);
assert.strictEqual(notes.length, 1); assert.ok(notes[0].note.includes('Offer A or B')); assert.strictEqual(notes[0].licence, undefined, 'import text never guesses a licence');
assert.ok(saved >= 2);
console.log('PASS art credits inheritance, grouped text, queries, packs, used-only output and opt-in checks');
